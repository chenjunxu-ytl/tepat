const assert=require('node:assert/strict');
const {html,segments}=require('../extension/results.js');
let parts=segments('Dr. Ali dan dr', [{start:12,end:14,level:'warning',note:'SMS'}]);
assert.equal(parts.filter(p=>p.level).map(p=>p.text).join(''),'dr');
parts=segments('😀 dokter', [{start:3,end:9,level:'warning',note:'ID'}]);
assert.equal(parts.find(p=>p.level).text,'dokter');
parts=segments('dokter', [{start:0,end:6,level:'warning',note:'word'}],3);
assert.equal(parts.map(p=>p.text).join(''),'dokter');
parts=segments('abc def',[{start:0,end:7,level:'info',note:'sentence'},{start:4,end:7,level:'error',note:'rule'}]);
assert.equal(parts.find(p=>p.text==='def').level,'error');
assert.equal(parts.find(p=>p.text==='def').notes.length,2);
const reminder={start:4,end:9,level:'info',category:'grammar',span:'ialah',note:'Check predicate context',highlight:false};
parts=segments('Ali ialah doktor.',[reminder]);
assert(parts.every(p=>p.level===null));
assert(html({engine:'evidence-v2',issues:[reminder]}).includes('Check predicate context'));
parts=segments('Ali ialah adalah doktor.',[{...reminder,start:4,end:16},{start:4,end:16,level:'error',note:'Repeated pemeri',highlight:true}]);
assert.equal(parts.find(p=>p.text==='ialah adalah').level,'error');
const output=html({engine:'evidence-v2',issues:[{level:'warning',category:'spelling',span:'<script>x</script>',note:'"onclick=x',suggestion:'a&b'}],coverage:{},total_words:1});
assert(!output.includes('<script>'));assert(output.includes('&lt;script&gt;'));
assert(html({engine:'evidence-v2',issues:[]}).includes('Whole-sentence accuracy and facts remain unverified'));
console.log('Result rendering / UTF-16 / occurrence / overlapping span checks passed');
